#!/usr/bin/env python3
"""make_assets.py - cut the generated cartoon art out of its white background,
crop/resize it, and embed everything as data URIs in js/assets.js so the game
works from file:// with no server.
Sources (assets/source/): gen_kevin_head.jpg, gen_kevin_keyart.jpg,
gen_zombie_heads.jpg, gen_title_bg.jpg (all generated from kevin_photo.jpg /
text prompts). Requires Pillow + numpy."""
import base64, io, os
import numpy as np
from PIL import Image, ImageFilter
from collections import deque

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'source')
OUT = os.path.join(ROOT, 'assets')

def cutout(img, tol=34):
    """flood-fill near-white background from the borders -> alpha"""
    a = np.asarray(img.convert('RGB')).astype(np.int16)
    h, w, _ = a.shape
    white = (a.min(axis=2) > 255 - tol) & ((a.max(axis=2) - a.min(axis=2)) < 30)
    bg = np.zeros((h, w), bool)
    q = deque()
    for x in range(w):
        for y in (0, h - 1):
            if white[y, x] and not bg[y, x]: bg[y, x] = True; q.append((y, x))
    for y in range(h):
        for x in (0, w - 1):
            if white[y, x] and not bg[y, x]: bg[y, x] = True; q.append((y, x))
    while q:
        y, x = q.popleft()
        for dy, dx in ((1,0),(-1,0),(0,1),(0,-1)):
            ny, nx = y+dy, x+dx
            if 0 <= ny < h and 0 <= nx < w and white[ny, nx] and not bg[ny, nx]:
                bg[ny, nx] = True; q.append((ny, nx))
    alpha = Image.fromarray(np.where(bg, 0, 255).astype(np.uint8))
    alpha = alpha.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(1.0))
    out = img.convert('RGBA'); out.putalpha(alpha)
    return out

def trim(im):
    bb = im.getchannel('A').point(lambda v: 255 if v > 20 else 0).getbbox()
    return im.crop(bb)

def fit(im, maxw, maxh):
    s = min(maxw / im.width, maxh / im.height, 1.0)
    return im.resize((max(1, round(im.width*s)), max(1, round(im.height*s))), Image.LANCZOS)

def uri(im, fmt='PNG', q=85):
    b = io.BytesIO()
    if fmt == 'JPEG': im.convert('RGB').save(b, 'JPEG', quality=q, optimize=True)
    else: im.save(b, 'PNG', optimize=True)
    return 'data:image/%s;base64,%s' % (fmt.lower(), base64.b64encode(b.getvalue()).decode())

assets = {}
# hero head (keeps the navy collar so it blends into the drawn polo)
head = trim(cutout(Image.open(os.path.join(SRC, 'gen_kevin_head.jpg'))))
head = fit(head, 300, 300); head.save(os.path.join(OUT, 'hero_head.png')); assets['heroHead'] = uri(head)
key = trim(cutout(Image.open(os.path.join(SRC, 'gen_kevin_keyart.jpg'))))
key = fit(key, 520, 700); key.save(os.path.join(OUT, 'hero_keyart.png')); assets['heroKeyart'] = uri(key)
# zombie heads: split the strip into 3 by empty columns
zh = cutout(Image.open(os.path.join(SRC, 'gen_zombie_heads.jpg')))
al = np.asarray(zh.getchannel('A')) > 20
cols = al.any(axis=0)
runs, start = [], None
for x, c in enumerate(cols):
    if c and start is None: start = x
    if not c and start is not None:
        if x - start > 40: runs.append((start, x))
        start = None
if start is not None: runs.append((start, len(cols)))
print('zombie head runs', runs)
for i, (x0, x1) in enumerate(runs[:3]):
    z = trim(zh.crop((x0, 0, x1, zh.height)))
    z = fit(z, 200, 200); z.save(os.path.join(OUT, 'zombie_head_%d.png' % i))
    assets['zHead%d' % i] = uri(z)
bg = Image.open(os.path.join(SRC, 'gen_title_bg.jpg')).convert('RGB')
bg = fit(bg, 1280, 720); bg.save(os.path.join(OUT, 'title_bg.jpg'), quality=82); assets['titleBg'] = uri(bg, 'JPEG', 80)
for i, n in enumerate(['portlouis','pereybere','chamarel','mountain','flicenflac','sea','sugarcane','samara']):
    b = Image.open(os.path.join(SRC, 'gen_bg%d_%s.jpg' % (i + 1, n))).convert('RGB')
    b = fit(b, 1280, 720); b.save(os.path.join(OUT, 'bg%d_%s.jpg' % (i + 1, n)), quality=80)
    assets['bg%d' % (i + 1)] = uri(b, 'JPEG', 74)
with open(os.path.join(ROOT, 'js', 'assets.js'), 'w') as f:
    f.write('// Generated by tools/make_assets.py - embedded images (data URIs) so the game runs from file://\n')
    f.write('window.ZR_ASSETS = {\n')
    for k, v in assets.items(): f.write('  %s: "%s",\n' % (k, v))
    f.write('};\n')
print({k: len(v) for k, v in assets.items()})
